SELECT
    COUNT(*) AS TOTAL_STUDENTS,
    ROUND(AVG(CGPA), 2) AS AVERAGE_CGPA,
    MAX(CGPA) AS HIGHEST_CGPA,
    MIN(CGPA) AS LOWEST_CGPA
FROM ANUDEEP_STUDENTS;


SELECT
    S.STUDENT_ID,
    S.STUDENT_NAME,
    S.DEPARTMENT,
    C.COURSE_NAME,
    C.CATEGORY,
    E.ENROLLMENT_DATE,
    E.ENROLLMENT_STATUS
FROM ANUDEEP_STUDENTS S
INNER JOIN ANUDEEP_ENROLLMENTS E
    ON S.STUDENT_ID = E.STUDENT_ID
INNER JOIN ANUDEEP_COURSES C
    ON E.COURSE_ID = C.COURSE_ID
ORDER BY S.STUDENT_ID;


SELECT
    S.STUDENT_ID,
    S.STUDENT_NAME,
    S.DEPARTMENT,
    COUNT(M.MARK_ID) AS TOTAL_SUBJECTS,
    ROUND(AVG(M.OBTAINED_MARKS), 2) AS AVERAGE_MARKS,
    SUM(M.OBTAINED_MARKS) AS TOTAL_MARKS
FROM ANUDEEP_STUDENTS S
INNER JOIN ANUDEEP_MARKS M
    ON S.STUDENT_ID = M.STUDENT_ID
GROUP BY
    S.STUDENT_ID,
    S.STUDENT_NAME,
    S.DEPARTMENT
ORDER BY AVERAGE_MARKS DESC;



SELECT
    STUDENT_ID,
    SUBJECT_NAME,
    OBTAINED_MARKS,

    ROUND(
        AVG(OBTAINED_MARKS) OVER(
            PARTITION BY STUDENT_ID
        ), 2
    ) AS STUDENT_AVERAGE

FROM ANUDEEP_MARKS
ORDER BY STUDENT_ID;



SELECT
    STUDENT_ID,
    STUDENT_NAME,
    DEPARTMENT,
    CGPA,

    ROUND(
        AVG(CGPA) OVER(
            PARTITION BY DEPARTMENT
        ), 2
    ) AS DEPARTMENT_AVERAGE

FROM ANUDEEP_STUDENTS
ORDER BY DEPARTMENT, CGPA DESC;





































































