-- ==========================================
-- CLEAN STUDENTS TABLE
-- ==========================================

CREATE OR REPLACE TABLE ANUDEEP_STUDENTS AS
SELECT
    TRY_TO_NUMBER(TRIM(STUDENT_ID)) AS STUDENT_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(STUDENT_NAME)), ''),
        'UNKNOWN'
    ) AS STUDENT_NAME,

    TRY_TO_NUMBER(NULLIF(TRIM(AGE), '')) AS AGE,

    COALESCE(
        NULLIF(UPPER(TRIM(GENDER)), ''),
        'UNKNOWN'
    ) AS GENDER,

    COALESCE(
        NULLIF(UPPER(TRIM(DEPARTMENT)), ''),
        'UNKNOWN'
    ) AS DEPARTMENT,

    TRY_TO_DECIMAL(
        NULLIF(TRIM(CGPA), ''),
        4, 2
    ) AS CGPA,

    COALESCE(
        NULLIF(UPPER(TRIM(CITY)), ''),
        'UNKNOWN'
    ) AS CITY,

    LOWER(TRIM(EMAIL)) AS EMAIL

FROM ANUDEEP_STUDENTS_RAW_TABLE;


-- ==========================================
-- CLEAN COURSES TABLE
-- ==========================================

CREATE OR REPLACE TABLE ANUDEEP_COURSES AS
SELECT
    TRY_TO_NUMBER(TRIM(COURSE_ID)) AS COURSE_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(COURSE_NAME)), ''),
        'UNKNOWN'
    ) AS COURSE_NAME,

    COALESCE(
        NULLIF(UPPER(TRIM(CATEGORY)), ''),
        'UNKNOWN'
    ) AS CATEGORY,

    TRY_TO_DECIMAL(
        NULLIF(TRIM(COURSE_FEE), ''),
        10, 2
    ) AS COURSE_FEE,

    TRY_TO_NUMBER(
        NULLIF(TRIM(DURATION_MONTHS), '')
    ) AS DURATION_MONTHS

FROM ANUDEEP_COURSES_RAW_TABLE;



-- ==========================================
-- CLEAN ENROLLMENTS TABLE
-- ==========================================

CREATE OR REPLACE TABLE ANUDEEP_ENROLLMENTS AS
SELECT
    TRY_TO_NUMBER(TRIM(ENROLLMENT_ID)) AS ENROLLMENT_ID,

    TRY_TO_NUMBER(TRIM(STUDENT_ID)) AS STUDENT_ID,

    TRY_TO_NUMBER(TRIM(COURSE_ID)) AS COURSE_ID,

    TRY_TO_DATE(
        NULLIF(TRIM(ENROLLMENT_DATE), '')
    ) AS ENROLLMENT_DATE,

    COALESCE(
        NULLIF(UPPER(TRIM(ENROLLMENT_STATUS)), ''),
        'UNKNOWN'
    ) AS ENROLLMENT_STATUS

FROM ANUDEEP_ENROLLMENTS_RAW_TABLE;


-- ==========================================
-- CLEAN MARKS TABLE
-- ==========================================

CREATE OR REPLACE TABLE ANUDEEP_MARKS AS
SELECT
    TRY_TO_NUMBER(TRIM(MARK_ID)) AS MARK_ID,

    TRY_TO_NUMBER(TRIM(STUDENT_ID)) AS STUDENT_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(SUBJECT_NAME)), ''),
        'UNKNOWN'
    ) AS SUBJECT_NAME,

    TRY_TO_NUMBER(TRIM(SEMESTER)) AS SEMESTER,

    TRY_TO_NUMBER(TRIM(MAX_MARKS)) AS MAX_MARKS,

    TRY_TO_NUMBER(TRIM(OBTAINED_MARKS)) AS OBTAINED_MARKS

FROM ANUDEEP_MARKS_RAW_TABLE;


-- ==========================================
-- CLEAN FACULTY TABLE
-- ==========================================

CREATE OR REPLACE TABLE ANUDEEP_FACULTY AS
SELECT
    TRY_TO_NUMBER(TRIM(FACULTY_ID)) AS FACULTY_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(FACULTY_NAME)), ''),
        'UNKNOWN'
    ) AS FACULTY_NAME,

    COALESCE(
        NULLIF(UPPER(TRIM(DEPARTMENT)), ''),
        'UNKNOWN'
    ) AS DEPARTMENT,

    TRY_TO_NUMBER(
        NULLIF(TRIM(EXPERIENCE_YEARS), '')
    ) AS EXPERIENCE_YEARS,

    COALESCE(
        NULLIF(UPPER(TRIM(CITY)), ''),
        'UNKNOWN'
    ) AS CITY

FROM ANUDEEP_FACULTY_RAW_TABLE;


-- ==========================================
-- CLEAN ATTENDANCE TABLE
-- ==========================================

CREATE OR REPLACE TABLE ANUDEEP_ATTENDANCE AS
SELECT
    TRY_TO_NUMBER(TRIM(ATTENDANCE_ID)) AS ATTENDANCE_ID,

    TRY_TO_NUMBER(TRIM(STUDENT_ID)) AS STUDENT_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(SUBJECT_NAME)), ''),
        'UNKNOWN'
    ) AS SUBJECT_NAME,

    TRY_TO_NUMBER(TRIM(TOTAL_CLASSES)) AS TOTAL_CLASSES,

    TRY_TO_NUMBER(TRIM(ATTENDED_CLASSES)) AS ATTENDED_CLASSES,

    TRY_TO_DATE(
        NULLIF(TRIM(ATTENDANCE_DATE), '')
    ) AS ATTENDANCE_DATE

FROM ANUDEEP_ATTENDANCE_RAW_TABLE;

